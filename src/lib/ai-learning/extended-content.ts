import type { AiLessonContent } from "./content";

// Short tuples keep authored lessons readable; the UI receives the same full lesson shape.
type Draft = {
  goal: string;
  terms: [string, string][];
  guide: [string, string][];
  flow: string[];
  example: [string, string];
  situation: string;
  question: string;
  choices: [string, string, string][];
  quiz: [string, [string, string, string], number, string];
  takeaway: string;
  sources: [string, string][];
};
function lesson(d: Draft): AiLessonContent {
  return {
    goal: d.goal,
    terms: d.terms.map(([word, meaning]) => ({ word, meaning })),
    guide: d.guide.map(([title, body]) => ({ title, body })),
    flow: d.flow,
    example: {
      title: d.example[0],
      code: d.example[1],
      language: "설계 예시",
      note: "동작을 이해하기 위해 만든 학습용 예시이며, 실행 가능한 설정이나 실제 도구의 출력은 아닙니다. 설치와 연동 방법은 아래 공식 문서에서 확인하세요.",
    },
    exercise: {
      situation: d.situation,
      question: d.question,
      choices: d.choices.map(([label, result, explanation]) => ({ label, result, explanation })),
    },
    quiz: { question: d.quiz[0], choices: d.quiz[1], answer: d.quiz[2], explanation: d.quiz[3] },
    takeaway: d.takeaway,
    sources: d.sources.map(([title, url]) => ({ title, url })),
  };
}

